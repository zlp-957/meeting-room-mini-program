_BLD_RIGHT = ("rrects", 12, 8.5, 19, 21, 1, 2)
_BLD_GROUND = ("cap", 2, 21, 21, 21, 2)
_BLD_WIN = ("cap", 5.5, 10.5, 10, 10.5, 0.9)
# 选中态：两楼填实，窗线反白（挖空），地面线保留 —— 墨量从线稿的 ~20% 提到 ~52%
# 选中态不填实 —— images/tabbar 下在用的那套原图标（日历 / 人像 / 拱门）两态形状完全相同，
# 只换颜色。这跟本文件早年「线稿→实心」的设计不同，但真机上要的是跟前两个一致，
# 不是跟废弃方案一致。

