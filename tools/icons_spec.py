# ---------------------------------------------------------------- 会议室：两栋楼
# v3 换成建筑（用户参考图）：左楼高、右楼矮，两楼相贴共用 x=12 那条边，
# 底部一条地面线左右各伸出 1.5 单位，让「楼群」站在地上而不是浮着。
# 楼体给 R1 圆角而非直角：27px 下直角会被抗锯齿啃出小缺口。
#
# 窗只留一条、且线宽压到 0.9（边框是 2）—— 这是被 27px 逼出来的结论：
# 24 网格在 27px 屏幕上 1 单位只有 1.13px，参考图那种「左 3 右 2」、与边框同粗的窗格
# 渲染出来是 5 条 2px 黑杠，整块读成栅栏，楼体还被横切成几截。
# 实测（tools/_verify/room_variants.py，四种简化程度并排）：0 条最干净、1 条 0.9 宽还能读出
# 「楼上有窗」、2 条起开始糊。0.9 宽在 81px 下是 3px 细线，与 6.75px 的边框正好是参考图那种比例。
